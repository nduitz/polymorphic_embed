  end

  describe "cast embeds_many with map and sort_param and delete_param" do
    setup do
      posts = %{
        1 => post(%{"title" => "one"}),
        2 => post(%{"title" => "two"}),
        3 => post(%{"title" => "three"})
      }

      %{posts: posts, opts: [sort_param: :sort, drop_param: :drop]}
    end

    test "no sort or drop", %{posts: posts, opts: opts} do
      changeset = cast(%Author{}, %{"posts" => posts}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == ~w(one two three)
    end

    test "drop with string keys", %{posts: posts, opts: opts} do
      changeset = cast(%Author{}, %{"posts" => posts, "drop" => [2]}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == ["one", "three"]
    end

    test "drop with atom keys", %{posts: posts, opts: opts} do
      changeset = cast(%Author{}, %{posts: posts, drop: [2]}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == ["one", "three"]
    end

    test "sort with string keys", %{posts: posts, opts: opts} do
      changeset = cast(%Author{}, %{"posts" => posts, "sort" => [2, 3, 1]}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == ~w(two three one)
    end

    test "sort creates a new entry", %{opts: opts} do
      changeset = cast(%Author{}, %{sort: ["new"]}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == [nil]
    end

    test "drop replaces existing data", %{opts: opts} do
      changeset = cast(%Author{posts: [%Post{title: "one"}]}, %{drop: [0]}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.action) == [:replace]
    end

    test "partial sort and new entries", %{posts: posts, opts: opts} do
      changeset = cast(%Author{}, %{posts: posts, sort: [2, 3, 1]}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == ~w(two three one)

      changeset = cast(%Author{}, %{posts: posts, sort: [2]}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == ~w(two one three)

      changeset = cast(%Author{}, %{posts: posts, sort: [2, "new"]}, :posts, opts)

      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) ==
               ["two", nil, "one", "three"]
    end

    test "sort and drop together", %{posts: posts, opts: opts} do
      changeset = cast(%Author{}, %{posts: posts, sort: [3, 2, 1], drop: [2]}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == ["three", "one"]

      changeset =
        cast(%Author{}, %{posts: posts, sort: [1, "new"], drop: [2, "new"]}, :posts, opts)

      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == ["one", "three"]
    end

    test "sort and drop that are not lists", %{posts: posts, opts: opts} do
      changeset = cast(%Author{}, %{posts: posts, sort: :x, drop: :y}, :posts, opts)

      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) ==
               ["one", "two", "three"]
    end
  end


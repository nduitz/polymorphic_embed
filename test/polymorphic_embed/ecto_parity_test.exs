# Mirrors test/ecto/changeset/embedded_test.exs from Ecto v3.12.1.
#
# The goal is output parity: for the same input, a polymorphic embed gives
# the same output as an Ecto embed. Each test keeps the name and the
# assertions of the Ecto test. The only changes are the ones a polymorphic
# field needs: a type key in the params, cast_polymorphic_embed/3 in place of
# cast_embed/3, `with:` as a keyword list of types, and
# PolymorphicEmbed.traverse_errors/2. Tests for Ecto features that
# polymorphic embeds do not have are left out.
defmodule PolymorphicEmbed.EctoParityTest do
  use ExUnit.Case, async: true

  alias Ecto.Changeset

  alias __MODULE__.{Author, Post, Profile}

  defmodule Post do
    use Ecto.Schema
    import Ecto.Changeset

    # Ecto uses `schema "posts"`. Polymorphic embeds generate ids at cast time
    # and crash on an autogenerated integer id, see the test for AutoIdPost.
    @primary_key {:id, :id, autogenerate: false}
    schema "posts" do
      field :title, :string
      field :position, :integer
    end

    def changeset(schema, params) do
      cast(schema, params, ~w(title)a)
      |> validate_required(:title)
      |> validate_length(:title, min: 3)
    end

    def optional_changeset(schema, params) do
      cast(schema, params, ~w(title)a)
    end
  end

  defmodule Profile do
    use Ecto.Schema
    import Ecto.Changeset

    embedded_schema do
      field :name
    end

    def changeset(schema, params) do
      cast(schema, params, ~w(name id)a)
      |> validate_required(:name)
      |> validate_length(:name, min: 3)
    end

    def optional_changeset(schema, params) do
      cast(schema, params, ~w(name)a)
    end
  end

  defmodule AutoIdPost do
    use Ecto.Schema

    schema "posts" do
      field :title, :string
    end

    def changeset(schema, params), do: Ecto.Changeset.cast(schema, params, [:title])
  end

  defmodule Author do
    use Ecto.Schema
    import PolymorphicEmbed

    # Polymorphic embeds only accept on_replace: :update for one and
    # on_replace: :delete for many.
    schema "authors" do
      field :name, :string
      polymorphic_embeds_one :profile, types: [profile: Profile], on_replace: :update
      polymorphic_embeds_many :posts, types: [post: Post], on_replace: :delete
      polymorphic_embeds_many :auto_id_posts, types: [post: AutoIdPost], on_replace: :delete
    end
  end

  defp cast(schema, params, embed, opts \\ []) do
    schema
    |> Changeset.cast(params, ~w())
    |> PolymorphicEmbed.cast_polymorphic_embed(embed, opts)
  end

  defp profile(params), do: Map.put(params, "__type__", "profile")
  defp post(params), do: Map.put(params, "__type__", "post")

  ## Cast embeds one

  test "cast embeds_one with valid params" do
    changeset = cast(%Author{}, %{"profile" => profile(%{"name" => "michal"})}, :profile)
    profile = changeset.changes.profile
    assert profile.changes == %{name: "michal"}
    assert profile.errors == []
    assert profile.action == :insert
    assert profile.valid?
    assert changeset.valid?
  end

  test "cast embeds_one with invalid params" do
    changeset = cast(%Author{}, %{"profile" => profile(%{})}, :profile)
    assert changeset.changes.profile.changes == %{}
    assert changeset.changes.profile.errors == [name: {"can't be blank", [validation: :required]}]
    assert changeset.changes.profile.action == :insert
    refute changeset.changes.profile.valid?
    refute changeset.valid?
  end

  test "cast embeds_one with invalid params: string" do
    changeset = cast(%Author{}, %{"profile" => "value"}, :profile, required: true)
    assert changeset.errors == [profile: {"is invalid", [validation: :embed, type: :map]}]
    refute changeset.valid?
  end

  test "cast embeds_one with invalid params: list" do
    changeset = cast(%Author{}, %{"profile" => [profile(%{"name" => "michal"})]}, :profile)
    assert changeset.changes == %{}
    assert changeset.errors == [profile: {"is invalid", [validation: :embed, type: :map]}]
  end

  test "cast embeds_one with existing struct updating" do
    changeset =
      cast(
        %Author{profile: %Profile{name: "michal", id: "michal"}},
        %{"profile" => profile(%{"name" => "new", "id" => "michal"})},
        :profile
      )

    profile = changeset.changes.profile
    assert profile.changes == %{name: "new"}
    assert profile.errors == []
    assert profile.action == :update
    assert profile.valid?
    assert changeset.valid?
  end

  test "cast embeds_one with existing struct updating from atom params" do
    # Emulate atom params from nested associations
    changeset =
      Changeset.cast(%Author{profile: %Profile{name: "michal", id: "michal"}}, %{}, ~w())

    changeset =
      put_in(changeset.params, %{"profile" => %{name: "new", id: "michal", __type__: "profile"}})

    changeset = PolymorphicEmbed.cast_polymorphic_embed(changeset, :profile, [])
    profile = changeset.changes.profile
    assert profile.changes == %{name: "new"}
    assert profile.errors == []
    assert profile.action == :update
    assert profile.valid?
    assert changeset.valid?
  end

  test "cast embeds_one without changes skips" do
    changeset =
      cast(
        %Author{profile: %Profile{name: "michal", id: "michal"}},
        %{"profile" => profile(%{"id" => "michal"})},
        :profile
      )

    assert changeset.changes == %{}
    assert changeset.errors == []
  end

  test "cast embeds_one when required" do

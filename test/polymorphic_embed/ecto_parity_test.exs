    assert changeset.changes == %{}

    changeset = cast(%Author{profile: %Profile{}}, %{}, :profile)
    assert changeset.changes == %{}
  end

  test "cast embeds_one with on_replace: :update" do
    schema = %Author{name: "Enio", profile: %Profile{id: "id", name: "Enio"}}

    changeset = cast(schema, %{"profile" => profile(%{"name" => "Jose"})}, :profile)
